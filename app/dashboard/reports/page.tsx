"use client";

import { useEffect, useMemo, useState } from "react";
import { Button, Card, KeyValues, Loading, Page, PageHeader, SectionTitle, StatusPill, Table, Tabs, ago } from "@/components/ds";

type Action = { id: string; priority: string; type: string; title: string; createdAt: string; participantCode: string | null };
type Data = { study: { name: string }; overview: { participants: number; critical: number; unresolved: number; findings: number; documents: number }; findingMix: { label: string; value: number }[]; actions: Action[] };

export default function ReportsPage() {
  const [data, setData] = useState<Data | null>(null);
  const [scope, setScope] = useState<"all" | "high">("all");
  useEffect(() => { fetch("/api/dashboard", { cache: "no-store" }).then((r) => r.json()).then((r) => r.success && setData(r.data)).catch(() => {}); }, []);
  const rows = useMemo(() => (data?.actions ?? []).filter((a) => scope === "all" || a.priority === "HIGH"), [data, scope]);
  if (!data) return <Page><Loading label="Loading reports" /></Page>;
  const max = Math.max(1, ...data.findingMix.map((m) => m.value));

  return (
    <Page>
      <style>{`@media print { aside, header, .no-print { display: none !important; } main { overflow: visible !important; } body { background: white; } }`}</style>
      <div className="space-y-6">
        <PageHeader title="Study report" lead={`What TrialIQ has checked in ${data.study?.name || "this workspace"} and what is still open. Export it for a study meeting or monitor visit.`}
          actions={<Button kind="primary" className="no-print" onClick={() => window.print()}>Export PDF</Button>}>
          <KeyValues items={[
            { k: "Checks saved", v: data.overview.findings },
            { k: "Open for sign-off", v: `${data.overview.unresolved}${data.overview.critical ? `, ${data.overview.critical} high priority` : ""}` },
            { k: "Participants", v: data.overview.participants },
            { k: "Source documents", v: data.overview.documents },
          ]} />
        </PageHeader>

        <section>
          <SectionTitle title="Checks run by type" />
          <Card as="div" className="space-y-3 p-5">
            {data.findingMix.length ? data.findingMix.map((m) => (
              <div key={m.label} className="grid grid-cols-[200px_1fr_40px] items-center gap-3 text-[13px]">
                <span className="truncate text-ink">{m.label}</span>
                <span className="h-2 rounded-full bg-page"><span className="block h-2 rounded-full bg-primary" style={{ width: `${(m.value / max) * 100}%` }} /></span>
                <span className="text-right font-medium text-ink-2">{m.value}</span>
              </div>
            )) : <p className="text-sm text-ink-2">No checks saved yet.</p>}
          </Card>
        </section>

        <section className="space-y-3">
          <SectionTitle title="Open items" count={rows.length} />
          <div className="no-print"><Tabs label="Report scope" value={scope} onChange={setScope} items={[{ id: "all", label: "All open" }, { id: "high", label: "High priority" }]} /></div>
          {rows.length ? (
            <Table head={["Finding", "Check", "Participant", "Priority", "Raised"]} rows={rows.map((a) => [
              <span key="t" className="font-medium">{a.title}</span>, a.type, a.participantCode ? <span key="p" className="font-mono text-xs">{a.participantCode}</span> : "Study", <StatusPill key="s" tone={a.priority === "HIGH" ? "no" : "rev"}>{a.priority === "HIGH" ? "High" : "Review"}</StatusPill>, ago(a.createdAt),
            ])} />
          ) : <Card as="div" className="p-5 text-sm text-ink-2">Nothing open in this scope.</Card>}
        </section>
        <p className="text-xs text-ink-3">Generated by TrialIQ from synthetic demo records on {new Date().toLocaleDateString()}. Every finding is a draft until a qualified person signs it off.</p>
      </div>
    </Page>
  );
}
